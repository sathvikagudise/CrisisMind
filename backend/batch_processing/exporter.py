import io
import csv
import logging
from typing import Optional

from backend.batch_processing.response import BatchFileResult, BatchSummary

logger = logging.getLogger("crisismind")


def export_csv(results: list[BatchFileResult], summary: Optional[BatchSummary] = None) -> str:
    output = io.StringIO()
    fieldnames = [
        "filename", "success", "severity", "confidence", "priority",
        "infrastructure_impact", "emergency_level", "recommended_actions",
        "processing_time_ms", "error",
    ]
    writer = csv.DictWriter(output, fieldnames=fieldnames)
    writer.writeheader()

    for r in results:
        writer.writerow({
            "filename": r.filename,
            "success": r.success,
            "severity": r.severity or "",
            "confidence": f"{r.confidence:.2f}" if r.confidence is not None else "",
            "priority": r.priority or "",
            "infrastructure_impact": r.infrastructure_impact or "",
            "emergency_level": r.emergency_level or "",
            "recommended_actions": "; ".join(r.recommended_actions),
            "processing_time_ms": f"{r.processing_time_ms:.1f}",
            "error": r.error or "",
        })

    return output.getvalue()


def export_pdf_text(results: list[BatchFileResult], summary: Optional[BatchSummary] = None) -> str:
    lines = []
    lines.append("=" * 70)
    lines.append("CRISIS MIND — BATCH ANALYSIS REPORT")
    lines.append("=" * 70)
    lines.append("")

    if summary:
        lines.append(f"Total files:        {summary.total_files}")
        lines.append(f"Successful:         {summary.successful}")
        lines.append(f"Failed:             {summary.failed}")
        lines.append(f"High Priority:      {summary.high_priority}")
        lines.append(f"Medium Priority:    {summary.medium_priority}")
        lines.append(f"Low Priority:       {summary.low_priority}")
        lines.append(f"Avg Confidence:     {summary.avg_confidence:.1f}%")
        lines.append(f"Avg Processing Time: {summary.avg_processing_time_ms:.0f}ms")
        lines.append("")
        lines.append("Severity Distribution:")
        for sev, cnt in sorted(summary.severity_distribution.items()):
            lines.append(f"  {sev}: {cnt}")
        lines.append("")
        lines.append("Priority Distribution:")
        for pri, cnt in sorted(summary.priority_distribution.items()):
            lines.append(f"  {pri}: {cnt}")
        lines.append("")

    lines.append("-" * 70)
    lines.append("INDIVIDUAL RESULTS")
    lines.append("-" * 70)
    lines.append("")

    for r in results:
        status = "OK" if r.success else "FAIL"
        lines.append(f"  [{status}] {r.filename}")
        if r.success:
            lines.append(f"         Severity: {r.severity}")
            lines.append(f"         Confidence: {r.confidence:.1f}%")
            lines.append(f"         Priority: {r.priority}")
            lines.append(f"         Emergency: {r.emergency_level}")
            lines.append(f"         Actions: {'; '.join(r.recommended_actions)}")
        else:
            lines.append(f"         Error: {r.error}")
        lines.append(f"         Time: {r.processing_time_ms:.0f}ms")
        lines.append("")

    lines.append("=" * 70)
    lines.append("END OF REPORT — Generated by CrisisMind AI")
    lines.append("=" * 70)

    return "\n".join(lines)


def compute_summary(results: list[BatchFileResult]) -> BatchSummary:
    total = len(results)
    successful = sum(1 for r in results if r.success)
    failed = total - successful
    high = sum(1 for r in results if r.priority == "High")
    medium = sum(1 for r in results if r.priority == "Medium")
    low = sum(1 for r in results if r.priority == "Low")

    confidences = [r.confidence for r in results if r.confidence is not None]
    avg_conf = sum(confidences) / len(confidences) if confidences else 0

    times = [r.processing_time_ms for r in results]
    avg_time = sum(times) / len(times) if times else 0

    sev_dist: dict[str, int] = {}
    for r in results:
        if r.severity:
            sev_dist[r.severity] = sev_dist.get(r.severity, 0) + 1

    pri_dist: dict[str, int] = {}
    for r in results:
        if r.priority:
            pri_dist[r.priority] = pri_dist.get(r.priority, 0) + 1

    return BatchSummary(
        total_files=total,
        successful=successful,
        failed=failed,
        high_priority=high,
        medium_priority=medium,
        low_priority=low,
        avg_confidence=round(avg_conf, 2),
        avg_processing_time_ms=round(avg_time, 2),
        severity_distribution=sev_dist,
        priority_distribution=pri_dist,
    )
