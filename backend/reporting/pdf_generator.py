"""PDF report generation using fpdf2."""

import io
import logging
from datetime import datetime

from fpdf import FPDF

from backend.reporting.templates import (
    COLOR_PRIMARY, COLOR_SECONDARY, COLOR_ACCENT,
    COLOR_BG_LIGHT, COLOR_TEXT, COLOR_TEXT_MUTED,
    COLOR_BORDER, COLOR_WHITE, COLOR_GREEN, COLOR_YELLOW, COLOR_RED,
    SEVERITY_COLORS, PRIORITY_COLORS, SECTION_TITLES,
)

logger = logging.getLogger("crisismind.reporting")

REPORT_WIDTH = 190
LEFT_MARGIN = 10

# PyFPDF 1.x core fonts cannot render anything outside Latin-1 (and crash on
# C1 controls). Sanitize the whole report tree right before rendering so no
# unmappable character can ever reach fpdf, regardless of upstream gaps.
_PDF_SAFE_RE = __import__("re").compile(r"[^\t\n\r\x20-\x7E\xA0-\xFF]")


def _deep_sanitize(obj):
    if isinstance(obj, str):
        return _PDF_SAFE_RE.sub("", obj)
    if isinstance(obj, list):
        return [_deep_sanitize(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _deep_sanitize(v) for k, v in obj.items()}
    return obj


class ReportPDF(FPDF):
    def header(self):
        # Top accent bar
        self.set_fill_color(*COLOR_PRIMARY)
        self.rect(0, 0, 210, 4, "F")
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*COLOR_TEXT_MUTED)
        self.cell(0, 10, f"Generated by CrisisMind  |  AI-Powered Disaster Intelligence Platform  |  Page {self.page_no()}/{{nb}}", align="C")

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*COLOR_SECONDARY)
        self.set_fill_color(*COLOR_BG_LIGHT)
        self.cell(REPORT_WIDTH, 8, f"  {title}", fill=True, ln=True)
        self.ln(2)

    def info_row(self, label: str, value: str):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*COLOR_TEXT_MUTED)
        self.cell(55, 6, label)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*COLOR_TEXT)
        self.cell(0, 6, value, ln=True)

    def badge_cell(self, label: str, value: str, color_map: dict):
        color = color_map.get(value, COLOR_TEXT_MUTED)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*color)
        self.cell(55, 6, label)
        self.set_text_color(*color)
        self.set_font("Helvetica", "", 9)
        self.cell(0, 6, value, ln=True)


def _render_single_report(pdf: ReportPDF, report: dict):
    """Render one report onto the current PDF page."""
    # Account for page break - add page if starting a new sub-report in batch
    if pdf.get_y() > 240:
        pdf.add_page()

    # ── Incident Information ─────────────────────────────────────────
    pdf.section_title(SECTION_TITLES["incident"])
    pdf.info_row("Analysis ID", report["analysis_id"])
    pdf.info_row("Analysis Mode", report["analysis_mode"])
    pdf.info_row("Disaster Type", report["disaster_type"])
    pdf.info_row("Country", report["country"])
    pdf.info_row("Source", report["source"])
    pdf.info_row("Timestamp", report["timestamp_formatted"])

    title = report.get("event_title") or report.get("filename", "")
    if title:
        pdf.info_row("Event / File", title)
    pdf.ln(2)

    # Description
    desc = report.get("description", "")
    if desc:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*COLOR_TEXT_MUTED)
        pdf.multi_cell(REPORT_WIDTH, 4.5, f'"{desc}"')
        pdf.ln(1)

    # ── Prediction Summary ───────────────────────────────────────────
    pdf.section_title(SECTION_TITLES["prediction"])

    sev = report.get("severity", "N/A")
    sev_color = SEVERITY_COLORS.get(sev, COLOR_TEXT_MUTED)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*sev_color)
    pdf.cell(REPORT_WIDTH, 7, f"Severity: {sev}", ln=True)

    conf = report.get("confidence")
    conf_str = f"{conf:.1f}%" if conf is not None else "N/A"
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*COLOR_TEXT)
    pdf.info_row("Confidence", conf_str)
    pdf.info_row("Model Used", report.get("model_used", "N/A"))
    pdf.info_row("Processing Time", f"{report.get('processing_time_ms', 0):.0f} ms")
    pdf.ln(2)

    # ── Emergency Assessment ─────────────────────────────────────────
    pdf.section_title(SECTION_TITLES["assessment"])

    pri = report.get("priority", "N/A")
    pri_color = PRIORITY_COLORS.get(pri, COLOR_TEXT_MUTED)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*pri_color)
    pdf.cell(REPORT_WIDTH, 7, f"Priority: {pri}", ln=True)

    pdf.info_row("Infrastructure Impact", report.get("infrastructure_impact", "N/A"))
    pdf.info_row("Emergency Level", report.get("emergency_level", "N/A"))
    pdf.ln(2)

    # ── Recommended Actions ──────────────────────────────────────────
    pdf.section_title(SECTION_TITLES["actions"])
    actions = report.get("recommended_actions", [])
    if actions:
        for i, action in enumerate(actions, 1):
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(*COLOR_TEXT)
            bullet_x = pdf.get_x() + 5
            pdf.set_x(bullet_x)
            pdf.cell(4, 5, "-")
            pdf.multi_cell(REPORT_WIDTH - 10, 5, action)
    else:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*COLOR_TEXT_MUTED)
        pdf.cell(REPORT_WIDTH, 5, "No specific actions recommended.", ln=True)
    pdf.ln(2)

    # ── AI Explanation (Grad-CAM) ─────────────────────────────────────
    overlay_path = report.get("explanation_overlay_path")
    if overlay_path:
        from pathlib import Path as PPath
        p = PPath(overlay_path)
        if p.exists():
            pdf.ln(2)
            pdf.section_title("AI Explanation (Grad-CAM)")
            pdf.set_font("Helvetica", "I", 8)
            pdf.set_text_color(*COLOR_TEXT_MUTED)
            pdf.multi_cell(REPORT_WIDTH, 4,
                "The heatmap below highlights image regions that most influenced the prediction. "
                "Bright red/yellow areas indicate higher contribution to the predicted severity.")
            pdf.ln(2)
            overlay_w = REPORT_WIDTH - 20
            pdf.image(str(p), x=LEFT_MARGIN + 10, w=overlay_w)
            pdf.ln(2)

    # ── Technical Details ────────────────────────────────────────────
    pdf.section_title(SECTION_TITLES["technical"])
    pdf.info_row("Analysis Engine", report.get("analysis_engine", "N/A"))
    pdf.info_row("Decision Engine", report.get("decision_engine", "N/A"))
    pdf.info_row("Model Version", report.get("model_version", "N/A"))


def generate_pdf(report: dict) -> bytes:
    report = _deep_sanitize(report)
    pdf = ReportPDF()
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    pdf.set_left_margin(LEFT_MARGIN)

    # ── Project Header ───────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 22)
    pdf.set_text_color(*COLOR_PRIMARY)
    pdf.cell(REPORT_WIDTH, 10, report["project_name"], align="L", ln=True)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*COLOR_TEXT_MUTED)
    pdf.cell(REPORT_WIDTH, 5, report["subtitle"], ln=True)

    pdf.ln(1)

    pdf.set_draw_color(*COLOR_PRIMARY)
    pdf.set_line_width(0.5)
    pdf.line(LEFT_MARGIN, pdf.get_y(), LEFT_MARGIN + REPORT_WIDTH, pdf.get_y())
    pdf.ln(3)

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*COLOR_SECONDARY)
    pdf.cell(REPORT_WIDTH, 8, report["report_title"], ln=True)

    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*COLOR_TEXT_MUTED)
    pdf.cell(REPORT_WIDTH, 4, f"Version {report['version']}  |  Generated {report['generated_at_formatted']}", ln=True)
    pdf.ln(4)

    # Check if this is a batch report with multiple sub-reports
    batch_reports = report.get("_batch_reports")
    if batch_reports:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*COLOR_TEXT_MUTED)
        pdf.cell(REPORT_WIDTH, 5, f"Batch contains {len(batch_reports)} file(s)", ln=True)
        pdf.ln(3)
        for i, sub in enumerate(batch_reports, 1):
            if i > 1:
                pdf.add_page()
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(*COLOR_SECONDARY)
            pdf.cell(REPORT_WIDTH, 7, f"Result {i} of {len(batch_reports)}", ln=True)
            pdf.ln(1)
            _render_single_report(pdf, sub)
    else:
        _render_single_report(pdf, report)

    # Bottom bar
    pdf.ln(5)
    pdf.set_draw_color(*COLOR_PRIMARY)
    pdf.set_line_width(0.3)
    pdf.line(LEFT_MARGIN, pdf.get_y(), LEFT_MARGIN + REPORT_WIDTH, pdf.get_y())

    out = pdf.output("", "S")  # "S" = return document as string (default prints to stdout!)
    if isinstance(out, str):
        return out.encode("latin-1", "replace")
    return bytes(out)
